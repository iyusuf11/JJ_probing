"""ABAA procedures: logging, measurement routines, and the active-run fit.
I've adapted the process from Križan, et al. Mater. Quantum Technol (2026) to run on a Keithley 2450 SMU. 
The functions are designed to be robust to crashes and interruptions, and to save data in a way that can be re-analyzed later.
Call setup() once after connecting, before any routine:

    import abaa
    abaa.setup(smu, sample=SAMPLE, data_dir=DATA_DIR, room_T_C=ROOM_T_C, r_short=R_SHORT)

Protocol: Križan, et al. Mater. Quantum Technol (2026).
"""
import datetime as dt
import json
import time
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import curve_fit

EVENT = {"iv": 0, "burst": 1, "ramp": 2}

BASE = {}  # jj -> list of baseline R readings
CAL = []   # (jj, V_A, R0, R_active, R_30min) calibration pairs for the stop rule

smu = None
SAMPLE = None
DATA_DIR = None
ROOM_T_C = None
R_SHORT = 260.0   # Ohm: below this a junction counts as shorted (gotta be careful with the 2450's current limit, which is 1e-2 A, so R_short should be above V_A / 1e-2)


def setup(instrument, sample, data_dir, room_T_C=None, r_short=260.0):
    """Tell the routines which instrument to use and where to save."""
    global smu, SAMPLE, DATA_DIR, ROOM_T_C, R_SHORT
    smu = instrument
    SAMPLE = sample
    DATA_DIR = Path(data_dir)
    ROOM_T_C = room_T_C
    R_SHORT = r_short
    DATA_DIR.mkdir(parents=True, exist_ok=True)


class RunLog:
    """Crash-safe CSV row by row; JSON for parameters; ddh5 export at the end."""
    ### mainly generated by claude 
    cols = ["t", "event", "iter", "V", "I", "R", "fit_res"]

    def __init__(self, jj, kind, **meta):
        if smu is None:
            raise RuntimeError("Call abaa.setup(smu, ...) first")
        stamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
        self.name = f"{stamp}_{SAMPLE}_{jj}_{kind}"
        self.csv = DATA_DIR / f"{self.name}.csv"
        self.meta = dict(sample=SAMPLE, jj=jj, kind=kind, start=stamp, room_T_C=ROOM_T_C,
                         four_wire=smu.four_wire, M=smu.m_pulses, t_pulse=smu.t_pulse,
                         t_blank=smu.t_blank, V_IV=smu.v_iv, N_IV=smu.n_iv,
                         NPLC_IV=smu.nplc_iv, **meta)
        self.save_meta()
        self.t0 = time.time()
        self.rows = []
        with open(self.csv, "w") as f:
            f.write(",".join(self.cols) + "\n")

    def save_meta(self):
        (DATA_DIR / f"{self.name}.json").write_text(json.dumps(self.meta, indent=2, default=str))

    def add(self, event, it, V=np.nan, I=np.nan, R=np.nan, fit_res=np.nan):
        row = [time.time() - self.t0, event, it, V, I, R, fit_res]
        self.rows.append(row)
        with open(self.csv, "a") as f:
            f.write(",".join(str(x) for x in row) + "\n")

    @property
    def df(self):
        return pd.DataFrame(self.rows, columns=self.cols)

    def finish(self, **more_meta):
        self.meta.update(more_meta)
        self.save_meta()
        try:
            from labcore.data.datadict import DataDict
            from labcore.data.datadict_storage import datadict_to_hdf5
            d = self.df
            dd = DataDict(
                t=dict(values=d.t.values, unit="s"),
                event=dict(values=d.event.map(EVENT).values, axes=["t"]),
                iter=dict(values=d.iter.values, axes=["t"]),
                V=dict(values=d.V.values, axes=["t"], unit="V"),
                I=dict(values=d.I.values, axes=["t"], unit="A"),
                R=dict(values=d.R.values, axes=["t"], unit="Ohm"),
                fit_res=dict(values=d.fit_res.values, axes=["t"]),
            )
            for k, v in self.meta.items():
                dd.add_meta(k, str(v))
            dd.validate()
            datadict_to_hdf5(dd, str(DATA_DIR / self.name))
        except Exception as ex:
            print(f"ddh5 export skipped ({ex!r}); CSV is complete: {self.csv}")


def measure_R(jj):
    log = RunLog(jj, "baseline")
    R, res = smu.iv()
    log.add("iv", 0, R=R, fit_res=res)
    log.finish(R=R)
    BASE.setdefault(jj, []).append(R)
    msg = f"{jj}: R = {R:.2f} Ohm  (fit residual {res * 100:.3f} %)"
    if len(BASE[jj]) > 1:
        r = np.array(BASE[jj])
        msg += f"   n = {len(r)}, re-land spread {np.ptp(r) / r.mean() * 100:.3f} %"
    print(msg)
    return R


def breakdown_ramp(jj, polarity=+1, v_step=0.01, v_max=2.0, dwell=0.2, ilim=1e-3, jump_frac=0.3):
    "raises the voltage in small steps until the junction fails, and records the voltage where that happened. Returns (V_bd, log)."
    "It destroys the JJ on purpose, which is why its only for JJ01 and JJ02. The result, V_BD, sets the V_A values for the rest of the calibration: section 8 uses 0.70, 0.75, and 0.80 V_bd"
    
    log = RunLog(jj, f"bdv_{'pos' if polarity > 0 else 'neg'}",
                 polarity=polarity, v_step=v_step, v_max=v_max, dwell=dwell, ilim=ilim) # start logging
    smu.set_ilim(ilim) # set the current limit to avoid destroying the SMU
    R0, _ = smu.iv() # measure the initial resistance and log it
    log.add("iv", 0, R=R0)
    smu.w(":SENS:CURR:NPLC 1") #swith from SWEEPS to Single point measurement mode, and ramping time is set by PC cuz we dont care about the timing of the ramp, we just want to see where it fails. The sweep mode is for the bursts and IV sweeps.
    smu.w(":SENS:CURR:RANG:AUTO ON")
    smu.set_range(2)
    V_bd, R_prev = None, None
    try: # highest voltage we go to is 2V
        #we go through the voltage range in steps of v_step, and at each step we set the voltage, wait for dwell seconds, measure the voltage and current, calculate R, and log it. If R drops by more than jump_frac, we assume JJ has failed and record the voltage at that point as V_bd. The loop continues until we reach v_max or the JJ dies.
        for k, v in enumerate(np.arange(v_step, v_max + v_step / 2, v_step)):
            smu.set_v(polarity * v)
            time.sleep(dwell)
            Vm, I = smu.read()
            R = Vm / I
            log.add("ramp", k, V=Vm, I=I, R=R)
            if smu.in_compliance(I) or (R_prev is not None and R < (1 - jump_frac) * R_prev):
                V_bd = float(v)
                break
            R_prev = R
    finally:
        smu.safe() #if something goes wrong or we inturrput, we set the SMU to a safe state (V=0, output off)
    R1, _ = smu.iv() # confirm the final resistance after the ramp and log it
    log.add("iv", 1, R=R1) 
    shorted = R1 < R_SHORT
    log.finish(R0=R0, R_after=R1, V_bd=V_bd, shorted=shorted)
    if V_bd is None:
        print(f"{jj}: no breakdown up to {v_max:.2f} V   R {R0:.1f} -> {R1:.1f} Ohm")
    else:
        print(f"{jj}: stop at {polarity * V_bd:+.3f} V   R {R0:.1f} -> {R1:.1f} Ohm   "
              + ("SHORTED" if shorted else "NOT shorted: check the I-V plot before trusting V_bd"))
    return V_bd, log


def tune(jj, V_A, t_max=1800, target_frac=None, R_stop=None, ilim_factor=3.0, jump_frac=0.02,
         print_every=20, R0=None):
    """Run a burst of pulses at V_A until the junction relaxes to target_frac above R0, or R_stop, or t_max. Returns a dict with the results."""
    log = RunLog(jj, "tune", V_A=V_A, t_max=t_max, target_frac=target_frac, R_stop=R_stop,
                 ilim_factor=ilim_factor)
    R_first, res = smu.iv()
    log.add("iv", 0, R=R_first, fit_res=res)
    R0 = R_first if R0 is None else R0            # R0 is the reference for all the percentages. stepped passes in R0, so later steps still count from the fresh JJ.
    smu.set_ilim(min(ilim_factor * V_A / R_first, 1e-2))  #The limit is 3× the expected pulse current, capped at 10 mA. For 5 kΩ at 0.85 V, that’s 510 µA, so normal pulses pass but a short hits the limit.
    print(f"{jj}: R = {R_first:.2f} Ohm (R0 = {R0:.2f})   V_A = {V_A:.3f} V   "
          f"I_lim = {smu.ilim * 1e6:.0f} uA")
    R, R_prev, n, reason = R_first, R_first, 0, "time cap"
    t_start = t_stop = time.time()
    try:
        while True: #One iteration is a 3.6 s burst plus an I-V, about 4–5 s in total. t_stop records when pulsing last ended, and hold measures its relaxation time from there
            n += 1
            b = smu.burst(V_A)
            t_stop = time.time()
            log.add("burst", n, V=V_A, I=max(b["I_pos"], b["I_neg"]))
            if b["compliance"]:
                raise RuntimeError(f"current limit during burst (I+ {b['I_pos']:.2e}, I- {b['I_neg']:.2e} A)")
            R, res = smu.iv()
            log.add("iv", n, R=R, fit_res=res)
            if R < R_SHORT:
                raise RuntimeError(f"R = {R:.1f} Ohm: shorted")
            if abs(R - R_prev) / R_prev > jump_frac:
                print(f"  jump at iteration {n}: {R_prev:.1f} -> {R:.1f} Ohm")
            R_prev = R
            # Stop conditions: R_stop, target_frac, or t_max. The first two are checked after each iteration, and the last is checked at the start of the next iteration (so the last burst may run a bit over t_max). Whichever condition is met first is recorded in reason. The loop can also be interrupted by the user or by a RuntimeError (e.g., shorted junction or compliance).
            if n % print_every == 0:
                print(f"  it {n:5d}   t = {t_stop - t_start:6.0f} s   R = {R:9.2f} Ohm   "
                      f"dR/R0 = {(R / R0 - 1) * 100:6.2f} %")
            if R_stop is not None and R >= R_stop:
                reason = "R_stop reached"; break
            if target_frac is not None and R / R0 - 1 >= target_frac:
                reason = "target reached"; break
            if t_stop - t_start >= t_max:
                break
    except KeyboardInterrupt:
        reason = "interrupted"
    except RuntimeError as ex:
        reason = f"ABORT: {ex}"
    finally:
        smu.safe()
    res = dict(jj=jj, V_A=V_A, R0=R0, R_start=R_first, R_active=R, dR_active=R / R0 - 1,
               iterations=n, pulses=n * smu.m_pulses, duration_s=t_stop - t_start,
               t_stop=t_stop, reason=reason, csv=str(log.csv))
    log.finish(**{k: v for k, v in res.items() if k != "csv"})
    print(f"{jj}: {reason}.  {n} iterations, {res['duration_s']:.0f} s,  "
          f"R {R_first:.2f} -> {R:.2f} Ohm  (dR/R0 = {res['dR_active'] * 100:+.2f} %)")
    return res #Note that R_active isn’t where the junction ends up. It keeps drifting upward after the pulses stop, by about 3 % at 30 min in Križan’s data. hold measures that drift, and the stop rule from section 10 corrects for it.


def hold(jj, t_stop, R0, t_max=1800, t_probe=60, print_every=10):
    """I-V every t_probe s; t measured from the last pulse. Returns (log, R at 30 min)."""
    log = RunLog(jj, "hold", t_max=t_max, t_probe=t_probe, R0=R0)
    log.t0 = t_stop
    k = 0
    try:
        while True:                          # last read is at or after t_max
            t_k = time.time()
            R, res = smu.iv()
            log.add("iv", k, R=R, fit_res=res)
            if k % print_every == 0:
                print(f"  t = {(t_k - t_stop) / 60:7.1f} min   R = {R:9.2f} Ohm   " 
                      f"dR/R0 = {(R / R0 - 1) * 100:+.3f} %")
            k += 1
            if t_k - t_stop >= t_max:
                break
            time.sleep(max(t_probe - (time.time() - t_k), 0))
            "read the resistance every t_probe seconds, and log it. The loop continues until t_max seconds have passed since the last pulse. The last read is at or after t_max. we read once every mintue, and print every 10 minutes. The loop can be interrupted, in which case we just exit and return the log and the last R."
    except KeyboardInterrupt:
        pass
    finally:
        smu.safe()
    d = log.df[log.df.event == "iv"]
    R30 = float(np.interp(1800, d.t, d.R)) if len(d) and d.t.max() >= 1800 else np.nan
    log.finish(n_reads=k, R_30min=R30)
    return log, R30


def tune_and_hold(jj, V_A, target_frac=0.10, t_max=1800, t_hold=1800, **kw):
    r = tune(jj, V_A, t_max=t_max, target_frac=target_frac, **kw)
    if r["reason"].startswith("ABORT"):
        return r
    lg, R30 = hold(jj, r["t_stop"], r["R0"], t_max=t_hold)
    r.update(R_30min=R30, dR_total=R30 / r["R0"] - 1, hold_csv=str(lg.csv))
    if np.isfinite(R30):
        CAL.append(dict(jj=jj, V_A=V_A, R0=r["R0"], R_active=r["R_active"], R_30min=R30))
        print(f"{jj}: R(30 min) = {R30:.2f} Ohm   relaxation = "
              f"{(R30 - r['R_active']) / r['R0'] * 100:+.2f} % of R0")
    return r



def fit_active(csv):
    d = pd.read_csv(csv)
    d = d[d.event == "iv"]
    t = (d.t - d.t.iloc[0]).values
    y = d.R.values / d.R.values[0] - 1
    (a, b), _ = curve_fit(lambda t, a, b: a * t + b * t ** 2, t, y, p0=(1e-4, 0.0))
    return dict(rate_pct_per_min=a * 6000, b=b, t=t, y=y, f=lambda tt: a * tt + b * tt ** 2)